/**
 * Escapes special HTML characters in a string to prevent HTML injection.
 * Use on every user-controlled value interpolated into an HTML email body.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#x27;");
}
